def detect_regions(toks):
    return [name for name, roots in REGIONS.items() if count_roots(toks, roots) > 0]


def normalize_regions(region_strings):
    """Регионы из профиля -> канонические имена из REGIONS (+ сами строки)."""
    out = set()
    for r in region_strings:
        toks = tokens(r)
        matched = detect_regions(toks)
        out.update(matched)
        if not matched:
            out.add(r.strip())
    return out


