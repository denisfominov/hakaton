def normalize_text(text):
    text = (text or "").lower().replace("ё", "е")
    return re.sub(r"\s+", " ", text).strip()


def tokens(text):
    return [t for t in WORD_RE.findall(normalize_text(text)) if len(t) > 1 and t not in STOPWORDS]


def stem(word):
    return _stemmer.stemWord(word)


def stems(text):
    return [stem(t) for t in tokens(text)]


def stem_text(text):
    return " ".join(stems(text))


def term_roots(term):
    """Корни для поиска термина профиля в тексте новости.

    Обрезаем стем ещё на одну букву у длинных слов — так ловится больше
    словоформ («поставщик/поставщиков», «тариф/тарифов»).
    """
    roots = []
    for s in stems(term):
        if len(s) >= 6:
            s = s[:-1]
        roots.append(s)
    return roots


def has_root(toks, root):
    if root.startswith("="):
        return root[1:] in toks
    if " " in root:
        # фраза: части должны идти подряд
        parts = root.split()
        n = len(parts)
        for i in range(len(toks) - n + 1):
            if all(toks[i + j].startswith(parts[j]) for j in range(n)):
                return True
        return False
    return any(t.startswith(root) for t in toks)


def count_roots(toks, roots):
    return sum(1 for r in roots if has_root(toks, r))


def term_in_text(term, toks):
    """Все значимые слова термина есть в тексте (порядок не важен)."""
    roots = term_roots(clean_name(term))
    if not roots:
        return False
    return all(any(t.startswith(r) for t in toks) for r in roots)


def clean_name(s):
    s = re.sub(r"\(.*?\)", " ", s or "")
    s = re.sub(r"[«»\"']", " ", s)
    return s.strip()


def paren_hint(s):
    m = re.search(r"\((.*?)\)", s or "")
    return m.group(1).strip() if m else ""


