def normalize_regions(region_strings):
    """Регионы из профиля -> канонические имена из REGIONS (+ сами строки)."""
    out = set()
    for r in region_strings:
        toks = tokens(r)
        matched = detect_regions(toks)
        out.update(matched)
        if not matched:
            out.add(r.strip())
    return out


