"""Ошибки LLM-слоя: общий модуль для клиента, бюджета и роутера."""


class LLMError(Exception):
    """Модель недоступна или ответ не годится — агент продолжает на правилах."""


class BudgetExceeded(LLMError):
    """Дневной лимит (₽ или токены) не позволяет сделать вызов — ответ правилами или из кэша."""
