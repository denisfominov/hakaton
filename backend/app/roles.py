def get(key):
    return ROLES.get(key or "") and {"key": key, **ROLES[key]}


def owner_matches(role, owner):
    o = (owner or "").lower()
    return any(k in o for k in role["owners"])


def area_rank(role, area):
    return role["areas"].index(area) if area in role["areas"] else len(role["areas"])


def catalog():
    return [{"key": k, "label": v["label"], "focus": v["focus"]} for k, v in ROLES.items()]


def actions_for(role, channels, limit=2):
    """Действия роли по каналам события: сначала каналы, важные роли, потом остальные. Формат — как у
    analysis.action (что сделать, почему, ответственный, срок)."""
    if not role or not channels:
        return []
    own, other = ROLE_ACTIONS.get(role["key"], {}), []
    ordered = [c for c in channels if c["key"] in role["channels"]] + [c for c in channels if c["key"] not in role["channels"]]
    out = []
    for c in ordered:
        if c["key"] in own and own[c["key"]][0] not in [a["title"] for a in out]:
            out.append(_action(role, own[c["key"]], c))
        if len(out) >= limit:
            break
    if not out:
        c = ordered[0]
        spec = ROLE_DEFAULTS[role["key"]]["opportunity" if c.get("type") == "opportunity" else "risk"]
        out.append(_action(role, spec, c))
    return out


def _action(role, spec, channel):
    title, description, why = spec
    t = (channel.get("title") or "").rstrip(".")
    return {"title": title, "description": f"{description} Канал влияния: «{t}»." if t else description,
            "why": why, "owner": role["label"],
            "due_days": 7 if channel.get("severity") == "high" else 14,
            "if_done": "Решение принято заранее, а не после того, как последствия проявятся.",
            "if_ignored": f"Последствия события станут для роли «{role['label']}» неожиданностью."}
